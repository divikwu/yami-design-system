import { mkdir, readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";

const endpoint = "https://ecapi.yami.com/ec-item/category_nav/template?pageScene=cms_main&customized_template=true&env=pre";
const locales = { en: "en_US", zh: "zh_CN" };

function absoluteUrl(value) {
  const url = new URL(value.startsWith("//") ? `https:${value}` : value);
  if (!['http:', 'https:'].includes(url.protocol)) throw new Error(`Unexpected category URL: ${value}`);
  return url.href;
}

function fontColor(value) {
  const color = value?.replace(/\s*!important\s*$/i, "").trim();
  if (!color) return undefined;
  if (!/^#(?:[\da-f]{3}|[\da-f]{6})$/i.test(color)) throw new Error(`Unexpected category color: ${value}`);
  return color;
}

function item(node, level = 0) {
  if (!node.nav_id || !node.nav_name) throw new Error("Category ID or name missing");
  const children = level === 0 ? node.columnSubCategoryNav.flat() : node.subCategoryNav ?? [];
  return {
    id: String(node.nav_id),
    label: node.nav_name,
    fontColor: fontColor(node.font_color),
    activeFontColor: fontColor(node.active_font_color),
    ...(node.link_url ? { href: absoluteUrl(node.link_url) } : {}),
    ...((level === 0 || level === 2) && node.image ? { image: { src: absoluteUrl(node.image), alt: "" } } : {}),
    ...(level === 2 && (node.img_ratio === 1 || node.img_ratio === 2) ? { imageRatio: node.img_ratio } : {}),
    ...(level === 0 && node.active_image ? { activeImage: { src: absoluteUrl(node.active_image), alt: "" } } : {}),
    ...(children.length ? { children: children.map((child) => item(child, level + 1)) } : {}),
  };
}

// Optional local response files reproduce a previously inspected capture.
const snapshots = await Promise.all(Object.entries(locales).map(async ([locale, language], index) => {
  const input = process.argv[index + 2];
  const response = input ? JSON.parse(await readFile(input, "utf8")) : await (async () => {
    const result = await fetch(endpoint, {
      headers: { y_language: language, y_platform: "pc", site_code: "us", channel: "2", "Content-Type": "application/json", token: "" },
      signal: AbortSignal.timeout(30_000),
    });
    if (!result.ok) throw new Error(`Category request failed: ${result.status}`);
    return result.json();
  })();
  if (String(response.success) !== "true" || response.body?.abResult !== "V1" || !response.body.categoryList?.length) {
    throw new Error(`Expected nonempty V1 categoryList for ${locale}`);
  }
  return [locale, {
    source: { endpoint, language, site: "us", version: "V1", capturedAt: new Date().toISOString() },
    items: response.body.categoryList.map((node) => item(node)),
  }];
}));

// Keep original source URLs in the snapshots and bundle exact local image copies.
const headerDirectory = new URL("../../packages/design-system/components/Header/", import.meta.url);
const imageDirectory = new URL("assets/category-menu/api/", headerDirectory);
await mkdir(imageDirectory, { recursive: true });
const sources = [...new Set(snapshots.flatMap(([, snapshot]) => snapshot.items.flatMap((node) => [node.image?.src, node.activeImage?.src].filter(Boolean))))].sort();
const entries = [];
for (let index = 0; index < sources.length; index += 4) {
  entries.push(...await Promise.all(sources.slice(index, index + 4).map(async (source) => {
    const filename = new URL(source).pathname.split("/").at(-1);
    if (!/^[a-f0-9]+_0x0\.(png|gif)$/.test(filename)) throw new Error(`Unexpected image filename: ${source}`);
    const response = await fetch(source, { signal: AbortSignal.timeout(30_000) });
    if (!response.ok || !response.headers.get("content-type")?.startsWith("image/")) throw new Error(`Image request failed: ${source}`);
    await writeFile(new URL(filename, imageDirectory), Buffer.from(await response.arrayBuffer()));
    return `  '${source}': new URL('./assets/category-menu/api/${filename}', import.meta.url).href,`;
  })));
}
await writeFile(new URL("category-menu.images.ts", headerDirectory), `// Generated by tooling/storybook/refresh-category-menu-fixture.mjs; do not edit.\nexport const categoryMenuImages: Record<string, string> = {\n${entries.join("\n")}\n}\n`);
console.log(`Downloaded ${sources.length} default/active category images`);

for (const [locale, snapshot] of snapshots) {
  const output = new URL(`../../packages/design-system/components/Header/category-menu.${locale}.json`, import.meta.url);
  await writeFile(output, `${JSON.stringify(snapshot, null, 2)}\n`);
  console.log(`Updated ${fileURLToPath(output)} (${snapshot.items.length} root categories)`);
}
